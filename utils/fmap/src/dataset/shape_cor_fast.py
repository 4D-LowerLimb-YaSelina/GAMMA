@DATASET_REGISTRY.register()
class SHREC19_r(ShapeDatasetFast):
    def __init__(self, *args, **kwargs):
        """
        Remeshed SHREC19 dataset.

        _P.S. SHREC'19 is special. If `phase=train`, the dataset will contain all shapes; if `phase=test`, it will contain the shape pairs appears in the `corres/` folders. Thus the train/test set will overlap._

        _P.S. SHREC'19's corres files are special. Instead of in the format of template -> current shape, it saves all combinations between shape x -> shape y. The ground-truth correspondence is only meaningful in a pair. Therefore, it's hard to define its behavior as a single shape dataset. In light of this:_

        - `get_corr()` will return `None`, for both `test` and `train` phase.
        - Setting `phase=test` will return the same dataset as `phase=train`. Proper behavior of `phase=test` will only be implemented in the pair shape dataset `PairSHREC19_r`.

        _P.S. The mesh 40.off should be obmitted as it's a partial shape._

        Args:
            phase (str): 'train' or 'test'.
            *args: additional arguments for the parent class `ShapeDatasetFast`.
            **kwargs: additional keyword arguments for the parent class `ShapeDatasetFast`.
        """
        super().__init__(*args, **kwargs)
        assert self.phase in ['train', 'test'], f'Invalid phase {self.phase}, only "test" and "train"'

        if self.phase == 'train':
            assert not self.return_corr, 'SHREC19_r dataset does not support return_corr in train phase.'

        assert len(self) == 44, f'SHREC19_r dataset should contain 44 human body shapes, but get {len(self)}.'

        # mesh id to index
        self.mesh_id2idx = {
            mesh_id: i for i, mesh_id in enumerate(self.mesh_ls)
        }

    def get_corr(self, index):
        """
        Since SHREC'19 dataset is not designed to have correspondence for a single shape, this method will return `None`.

        Args:
            index (int): Index of the mesh file.

        Returns:
            None 
        """
        return None


@DATASET_REGISTRY.register()
class PairSHREC19_r(PairShapeDataset):
    def __init__(self, *args, **kwargs):
        """
        Paired remeshed SCAPE dataset.

        Args:
            phase (str): 'train' or 'test'. If 'train', the dataset will contain all 51 shapes, but not all shape will have `corr`, thus `return_corr` must be `False`; if 'test', it will contain the shape pairs appears in the `corres/` folders. _P.S. The train/test set will overlap._
            *args: arguments for `SHREC19_r` and its parent class `PairShapeDataset`.
            **kwargs: keyword arguments for `SHREC19_r` and its parent class `PairShapeDataset`.
        """
        dataset = SHREC19_r(*args, **kwargs)
        super().__init__(dataset)

        if self.dataset.phase == 'test':
            self.combinations = []

            # ignore the shape 40, since it is a partial shape
            corr_files = list(filter(lambda x: '40' not in x, sorted(glob(str(self.dataset.data_root / 'corres' / '*.map')))))
            
            for file in corr_files:
                first_index, second_index = (Path(file).stem).split('_')
                self.combinations.append([
                    self.dataset.mesh_id2idx[first_index],
                    self.dataset.mesh_id2idx[second_index],
                ])

    def __getitem__(self, index):
        # get index
        first_index, second_index = self.combinations[index]

        item = dict()
        item['first'] = self.dataset[first_index]
        item['second'] = self.dataset[second_index]

        if self.dataset.phase == 'test' and self.dataset.return_corr:
            first_mesh_id = self.dataset.mesh_ls[first_index]
            second_mesh_id = self.dataset.mesh_ls[second_index]
            corr = np.loadtxt(self.dataset.data_root / 'corres' / f'{first_mesh_id}_{second_mesh_id}.map', dtype=np.int32) - 1  # minus 1 to start from 0
            
            item['first']['corr'] = torch.arange(0, len(corr)).long() # treat the first shape as template, thus the i-th vertex -> the i-th vertex
            item['second']['corr'] = torch.from_numpy(corr).long() # then the mapping in .map is from the template (the 1st shape) -> the 2nd shape

        return item
    

