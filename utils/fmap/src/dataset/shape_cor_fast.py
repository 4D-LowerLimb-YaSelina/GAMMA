@DATASET_REGISTRY.register()
class SHREC16(ShapeDatasetFast):
    def __init__(self, *args, **kwargs):
        """
        SHREC16 dataset contains 200 training shapes, categorised into 8 classes (humans and animals). Each class has a complete shape to which the partial shapes are matched.
        
        There are two types of partial shapes: CUTS (missing a large part) and HOLES (missing many small parts). The train/test splits are 120/200 for CUTS and 79/200 for HOLES.

        _P.S. The `*.vts` files are special. They are in the format of partial shape -> template shape. Therefore, `dataset[index]['corr']` are in opposite direction comparing with other datasets. This will be corrected in `PairSHREC16`._

        Args:
            phase (str): 'train' or 'test.
            *args: additional arguments for the parent class `ShapeDatasetFast`.
            **kwargs: additional keyword arguments for the parent class `ShapeDatasetFast`.
        """
        super().__init__(*args, **kwargs)
        assert self.phase in ['train', 'test'], f'Invalid phase {self.phase}, only "train" and "test" is allowed'

        if self.phase == 'train':
            assert '_test' not in str(self.data_root), 'SHREC16 train dataset is in `SHREC16/` folder. Make sure you are using the correct path.'
        
        else:
            assert '_test' in str(self.data_root), 'SHREC16 test dataset is in `SHREC16_test/` folder. Make sure you are using the correct path.'
        
        self.folder_name = self.data_root.stem

        if self.folder_name == 'null':
            self.return_corr = False # full dataset does not have correspondence, so we set it to False
            # map mesh name (== class name) to index
            self.class2index = {
                class_name: index
                for index, class_name in enumerate(self.mesh_ls)
            }


@DATASET_REGISTRY.register()
class PairSHREC16(PairShapeDataset):
    def __init__(self, data_root: str, cut_type: str = 'cuts', *args, **kwargs):
        """
        Paired SHREC'16 dataset between the full shapes and one of their corresponding partial shape (full-to-partial).

        ```
        {
            'first': full_shape_data,
            'second': partial_shape_data,
        }
        ```

        Args:
            data_root (str): The root directory of the SHREC'16 dataset. It should contain three subdirectories: `cuts`, `holes`, and `null` (full shapes).
            cut_type (str): The type of partial shape to use. It can be either 'cuts' or 'holes'.
            phase (str): 'train' or 'test'.
            *args: arguments for `SHREC16` and its parent class `PairShapeDataset`.
            **kwargs: keyword arguments for `SHREC16` and its parent class `PairShapeDataset`.
        """
        self.data_root = Path(data_root)
        self.cut_type = cut_type

        # load full dataset
        assert (self.data_root / 'null').is_dir(), f'null/ folder not found in {data_root}.'
        self.full_dataset = SHREC16(data_root=self.data_root / 'null', *args, **kwargs)

        # load partial dataset
        assert (self.data_root / self.cut_type).is_dir(), f'{self.cut_type}/ folder not found in {data_root}.'
        self.partial_dataset = SHREC16(data_root=self.data_root / cut_type, *args, **kwargs)

    def __getitem__(self, index):
        partial_shape_data = self.partial_dataset[index]
        class_name = partial_shape_data['name'].split('_')[1]
        full_shape_index = self.full_dataset.class2index[class_name]
        full_shape_data = self.full_dataset[full_shape_index]

        if self.partial_dataset.return_corr:
            corr = partial_shape_data['corr'] # partial -> full
            full_shape_data['corr'] = corr # treat the full shape as target, thus directly use partial -> full
            partial_shape_data['corr'] = torch.arange(0, len(corr)).long() # treat the partial shape as template, thus the i-th vertex -> the i-th vertex
        
        item = {
            'first': full_shape_data,
            'second': partial_shape_data,
        }

        return item
    
    def __len__(self):
        return len(self.partial_dataset)