@DATASET_REGISTRY.register()
class ShapeDatasetFast(Dataset):
    def __init__(
            self,
            data_root,
            phase: str = 'full',
            return_faces: bool =True,
            return_L: bool = False,
            return_mass: bool = True,
            num_evecs: int = 200,
            return_evecs: bool = True,
            return_grad: bool = True,
            return_corr: bool = False,
            return_dist: bool = False,
        ):

        # options
        self.data_root = Path(data_root)
        assert self.data_root.is_dir(), f'invalid data root: {data_root}.'

        self.phase = phase
        self.return_faces = return_faces
        self.return_evecs = return_evecs
        self.return_grad = return_grad
        self.return_L = return_L
        self.return_mass = return_mass
        self.return_corr = return_corr
        self.return_dist = return_dist
        self.num_evecs = num_evecs

        self.mesh_ls = self.get_mesh_ls()

    def get_mesh_ls(self):
        """
        Get the list mesh names as paths relative to `data_root/off` (without extensions `.off`)

        Returns:
            list: A list of strings.
        """
        return [
            str(Path(mesh_file).relative_to(self.data_root / 'off').with_suffix(''))
            for mesh_file in sorted(glob(str(self.data_root / 'off' / '*.off')))
        ]


    def __getitem__(self, index):
        item = {}

        # get shape name and load spectral npz
        item['name'] = self.mesh_ls[index]

        spectral_npz = self.get_spectral_npz(index)

        assert spectral_npz['k_eig'] >= self.num_evecs, 'not enough eigenvectors in spectral data'

        item['verts'] = torch.from_numpy(spectral_npz['verts'])

        if self.return_faces:
            item['faces'] = torch.from_numpy(spectral_npz['faces'])

        if self.return_L:
            item['L'] = sparse_np_to_torch(read_sp_mat(spectral_npz, 'L'))
            
        if self.return_mass:
            item['mass'] = torch.from_numpy(spectral_npz['mass'])

        if self.return_evecs:
            item['evecs'] = torch.from_numpy(spectral_npz['evecs'][:, :self.num_evecs])
            item['evecs_trans'] = torch.from_numpy(
                spectral_npz['evecs'][:, :self.num_evecs].T * spectral_npz['mass'][None]
            )  # p.s. this step could take around 1/3 of the __getittem__ runtime. could be optimized by precomputation
            item['evals'] = torch.from_numpy(spectral_npz['evals'][:self.num_evecs])

        if self.return_grad:
            item['gradX'] = sparse_np_to_torch(read_sp_mat(spectral_npz, 'gradX'))
            item['gradY'] = sparse_np_to_torch(read_sp_mat(spectral_npz, 'gradY'))
        
        if self.return_corr:
            item['corr'] = self.get_corr(index)

        if self.return_dist:
            item['dist'] = self.get_dist(index)

        return item
    
    def get_spectral_npz(self, index):
        """
        Read the spectral operator data for a given index.
        
        Args:
            index (int): Index of the mesh file.

        _P.S. Generated by `preprocess.py` script._
        """
        return np.load(self.data_root / 'spectral' / f'{self.mesh_ls[index]}.npz')

    def get_corr(self, index):
        """
        Get the correspondence for a given index.

        _P.S. Generated by `preprocess.py` script._

        Args:
            index (int): Index of the mesh file.

        Returns:
            torch.Tensor: Correspondence indices. Shape [V_t,] from the template shape to the target (current) shape. Vertex indices are 0-based.
        """
        return torch.from_numpy(np.loadtxt(
            self.data_root / 'corres' / f'{self.mesh_ls[index]}.vts',
            dtype=np.int32,
        ) - 1).long()  # minus 1 to start from 0

    def get_dist(self, index):
        """
        Get the distance matrix for a given index.

        _P.S. Generated by `preprocess.py` script._

        Args:
            index (int): Index of the mesh file.

        Returns:
            torch.Tensor: Distance matrix. Shape [V, V], where V is the number of vertices in the mesh.
        """
        return torch.from_numpy(np.load(
            self.data_root / 'dist' / f'{self.mesh_ls[index]}.npz'
        )['dist_mat'])

    def __len__(self):
        return len(self.mesh_ls)
    

class PairShapeDataset(Dataset):
    def __init__(self, dataset):
        """
        Paired shape dataset.

        Args:
            dataset: Single shape dataset
        """
        assert isinstance(dataset, ShapeDatasetFast), f'invalid input data type of dataset: {type(dataset)}'
        self.dataset = dataset
        self.combinations = list(product(range(len(dataset)), repeat=2))

    def __getitem__(self, index):
        # get index
        first_index, second_index = self.combinations[index]

        item = dict()
        item['first'] = self.dataset[first_index]
        item['second'] = self.dataset[second_index]

        return item

    def __len__(self):
        return len(self.combinations)
    

