@DATASET_REGISTRY.register()
class PairDT4D_H(PairShapeDataset):
    def __init__(self, inter_class: bool = False, *args, **kwargs):
        """
        Paired remeshed DT4D-H dataset.

        Args:
            inter_class (bool): If `True`, the dataset will contain pairs from different classes (inter-class). If `False`, the dataset will contain pairs from the same class (intra-class).
            phase (str): 'train' or 'test'.
            *args: arguments for `DT4D_H` and its parent class `PairShapeDataset`.
            **kwargs: keyword arguments for `DT4D_H` and its parent class `PairShapeDataset`.
        """
        dataset = DT4D_H(*args, **kwargs)
        assert isinstance(dataset, ShapeDatasetFast), f'invalid input data type of dataset: {type(dataset)}'
        self.dataset = dataset
        
        # if inter_class, gather all inter_class pairs in a set
        self.inter_class = inter_class

        if self.inter_class:
            self.class_pair = set()
            files = glob(str(self.dataset.data_root / 'corres' / 'cross_category_corres' / '*.vts'))

            for file in files:
                class1, class2 = Path(file).stem.split('_')
                self.class_pair.add((class1, class2))

        self.combinations = []

        for i in range(len(self.dataset)):
            for j in range(len(self.dataset)):
                class1 = Path(self.dataset.mesh_ls[i]).parent.stem
                class2 = Path(self.dataset.mesh_ls[j]).parent.stem
                
                if self.inter_class:
                    # if inter_class, only add pairs from different classes
                    if (class1, class2) in self.class_pair:
                        # both (class1, class2) & (class2, class1)
                        self.combinations.append((i, j))

                elif not self.inter_class:
                    # if intra_class, add pairs from the same class
                    if class1 == class2:
                        self.combinations.append((i, j))
    
    def __getitem__(self, index):
        # get index
        first_index, second_index = self.combinations[index]

        item = dict()
        item['first'] = self.dataset[first_index]
        item['second'] = self.dataset[second_index]

        if self.inter_class and self.dataset.return_corr:
            first_class = Path(self.dataset.mesh_ls[first_index]).parent.stem
            second_class = Path(self.dataset.mesh_ls[second_index]).parent.stem

            # inter-class correspondence: class1_template -> class2_template
            corr = np.loadtxt(
                self.dataset.data_root / 'corres' / 'cross_category_corres' / f'{first_class}_{second_class}.vts',
                dtype=np.int32,
            ) - 1 # minus 1 to start from 0

            # treat class1's template as the template shape
            # no need to change corr of shape 1, as it is already class1_template -> shape 1
            # for shape 2: class1_template -(corr)-> class2_template -(item['second']['corr'])-> shape 2
            item['second']['corr'] = item['second']['corr'][corr]

        return item


