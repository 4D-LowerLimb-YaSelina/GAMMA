@DATASET_REGISTRY.register()
class PairTOPKIDS(PairShapeDataset):
    def __init__(self, *args, **kwargs):
        """
        Paired TOPKIDS dataset.

        Args:
            phase (str): 'train' or 'test'. If 'train', the dataset will contain all 51 shapes, but not all shape will have `corr`, thus `return_corr` must be `False`; if 'test', it will contain the shape pairs appears in the `corres/` folders. _P.S. The train/test set will overlap. Only recommend as test set._
            *args: arguments for `TOPKIDS` and its parent class `PairShapeDataset`.
            **kwargs: keyword arguments for `TOPKIDS` and its parent class `PairShapeDataset`.
        """
        dataset = TOPKIDS(*args, **kwargs)
        super().__init__(dataset)

        if self.dataset.phase == 'test' and self.dataset.return_corr:
            self.combinations = []
            test_size = len(glob(str(self.dataset.data_root / 'corres' / '*.vts')))
            
            for index in range(test_size):
                first_index, second_index = 0, index + 1
                self.combinations.append([first_index, second_index])

    def __getitem__(self, index):
        # get index
        first_index, second_index = self.combinations[index]

        item = dict()
        item['first'] = self.dataset[first_index]
        item['second'] = self.dataset[second_index]

        if self.dataset.phase == 'test' and self.dataset.return_corr:
            f = lambda x: '0' + str(x) if x < 10 else str(x)
            corr = np.loadtxt(self.dataset.data_root / 'corres' / f'kid{f(second_index)}_ref.vts', dtype=np.int32) - 1  # minus 1 to start from 0
            item['second']['corr'] = torch.arange(0, len(corr)).long() # treat the second shape as template, thus the i-th vertex -> the i-th vertex
            item['first']['corr'] = torch.from_numpy(corr).long() # then the mapping in .vts is from the template (the 2nd shape) -> the 1st shape

        return item


